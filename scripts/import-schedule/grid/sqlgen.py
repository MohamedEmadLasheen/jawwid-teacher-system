"""Generates the one write the importer performs: a single PL/pgSQL block.

A DO block is one statement, so it is atomic on every execution path (psql,
the Management API): any failed check or constraint aborts it and nothing it
did persists. The block

  * takes a transaction-scoped advisory lock, so two imports cannot interleave;
  * refuses to run if the booked schedule changed since the plan was made
    (fingerprint mismatch) — the plan was reviewed against that exact state;
  * refuses to run if any planned provenance key already exists (a repeated
    run of the same plan inserts nothing);
  * re-checks every teacher and student exists and is not soft-deleted;
  * INSERTs lessons and participants only — no UPDATE, no DELETE, no other
    table — relying on the deployed exclusion constraints as the final guard
    against any teacher or student overlap;
  * asserts the inserted count equals the plan.
"""
from __future__ import annotations

import re

from .db import FINGERPRINT_SQL

ADVISORY_LOCK_KEY = 'jawwid-grid-schedule-import'
UUID_RE = re.compile(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')


def _lit(value: str) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def _uuid(value: str) -> str:
    if not UUID_RE.match(value):
        raise ValueError(f'not a uuid: {value!r}')
    return f"'{value}'::uuid"


def plan_items(outcomes) -> list[dict]:
    items = []
    for o in outcomes:
        if o.status != 'IMPORT':
            continue
        if not (0 <= o.start_minute <= 1439 and o.duration_minutes > 0 and o.start_minute + o.duration_minutes <= 1440):
            raise ValueError(f'{o.sheet}!{o.cell}: time outside the data model reached the plan')
        items.append({
            'source_sheet': o.sheet, 'source_cell': o.source_key, 'teacher_id': o.teacher_id,
            'day_of_week': o.day_of_week, 'start_minute': o.start_minute, 'duration_minutes': o.duration_minutes,
            'student_ids': sorted(o.student_ids),
        })
    keys = [(i['source_sheet'], i['source_cell']) for i in items]
    if len(keys) != len(set(keys)):
        raise ValueError('duplicate provenance key in plan')
    return items


def generate_sql(items: list[dict], fingerprint: str, plan_id: str) -> str:
    if not re.fullmatch(r'[0-9a-f]{32}', fingerprint):
        raise ValueError('fingerprint must be an md5 hex digest')
    out = [
        f'-- Grid schedule import, plan {plan_id}: {len(items)} lesson(s), '
        f'{sum(len(i["student_ids"]) for i in items)} participant row(s).',
        '-- Generated by scripts/import-schedule/grid. INSERT-only; atomic; refuses a changed schedule.',
        'DO $grid_import$',
        'DECLARE',
        '  v_fingerprint text;',
        '  v_lesson uuid;',
        '  v_inserted int := 0;',
        'BEGIN',
        f'  PERFORM pg_advisory_xact_lock(hashtext({_lit(ADVISORY_LOCK_KEY)}));',
        f'  SELECT ({FINGERPRINT_SQL}) INTO v_fingerprint;',
        f'  IF v_fingerprint IS DISTINCT FROM {_lit(fingerprint)} THEN',
        "    RAISE EXCEPTION 'grid import %: the booked schedule changed since the plan was made (fingerprint %); re-run the plan', "
        f"{_lit(plan_id)}, v_fingerprint;",
        '  END IF;',
    ]
    for i in items:
        students = ', '.join(_uuid(s) for s in i['student_ids'])
        ref = f"{i['source_sheet']}!{i['source_cell']}"
        out += [
            f'  -- {ref}',
            f"  IF EXISTS (SELECT 1 FROM public.lessons WHERE source_sheet = {_lit(i['source_sheet'])} AND source_cell = {_lit(i['source_cell'])}) THEN",
            f"    RAISE EXCEPTION 'grid import: % was already imported', {_lit(ref)};",
            '  END IF;',
            f"  IF NOT EXISTS (SELECT 1 FROM public.teachers WHERE id = {_uuid(i['teacher_id'])} AND NOT is_deleted) THEN",
            f"    RAISE EXCEPTION 'grid import: teacher for % is missing or deleted', {_lit(ref)};",
            '  END IF;',
            f"  IF (SELECT count(*) FROM public.students WHERE id = ANY (ARRAY[{students}]) AND NOT is_deleted) <> {len(i['student_ids'])} THEN",
            f"    RAISE EXCEPTION 'grid import: a student for % is missing or deleted', {_lit(ref)};",
            '  END IF;',
            '  INSERT INTO public.lessons (teacher_id, original_teacher_id, day_of_week, start_minute, duration_minutes,',
            '                              lifecycle_status, source_sheet, source_cell)',
            f"  VALUES ({_uuid(i['teacher_id'])}, {_uuid(i['teacher_id'])}, {int(i['day_of_week'])}, {int(i['start_minute'])}, "
            f"{int(i['duration_minutes'])}, 'active', {_lit(i['source_sheet'])}, {_lit(i['source_cell'])})",
            '  RETURNING id INTO v_lesson;',
            f'  INSERT INTO public.lesson_participants (lesson_id, student_id) SELECT v_lesson, s FROM unnest(ARRAY[{students}]) AS s;',
            '  v_inserted := v_inserted + 1;',
        ]
    out += [
        f'  IF v_inserted <> {len(items)} THEN',
        f"    RAISE EXCEPTION 'grid import: inserted % lessons, plan has {len(items)}', v_inserted;",
        '  END IF;',
        f"  RAISE NOTICE 'grid import %: inserted % lessons', {_lit(plan_id)}, v_inserted;",
        'END',
        '$grid_import$;',
        '',
    ]
    return '\n'.join(out)
